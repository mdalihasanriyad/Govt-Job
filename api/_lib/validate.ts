import { createHash } from 'node:crypto';

export type JobStatus = 'draft' | 'pending_review' | 'published';
export const JOB_STATUSES: JobStatus[] = ['draft', 'pending_review', 'published'];

export interface PositionInput {
  name: string;
  vacancies?: number;
}

export interface JobInput {
  slug?: string;
  organization: string;
  title: string;
  positions: PositionInput[];
  totalVacancies?: number;
  categorySlug: string;
  employmentType?: string;
  education?: string;
  experience?: string;
  ageLimit?: string;
  salary?: string;
  applicationFee?: string;
  applicationStart?: string;
  deadline?: string;
  publishedAt: string;
  description?: string;
  howToApply?: string;
  applyUrl?: string;
  sourceUrl?: string;
  circularRef?: string;
  seoTitle?: string;
  metaDescription?: string;
  featuredImage?: string;
  featured: boolean;
  verified: boolean;
  status?: JobStatus;
}

export const OPTIONAL_JOB_KEYS = [
  'totalVacancies', 'employmentType', 'education', 'experience', 'ageLimit', 'salary',
  'applicationFee', 'applicationStart', 'deadline', 'description', 'howToApply',
  'applyUrl', 'sourceUrl', 'circularRef', 'seoTitle', 'metaDescription', 'featuredImage',
] as const;

export type ParseResult<T> = { ok: true; value: T } | { ok: false; errors: Record<string, string> };

const CONTROL_CHARS = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g;

export function cleanString(value: unknown, multiline: boolean): string {
  let text = typeof value === 'string' ? value : '';
  text = text.replace(/\r\n?/g, '\n').replace(CONTROL_CHARS, '');
  if (!multiline) text = text.replace(/\s*\n\s*/g, ' ');
  return text.trim();
}

export function isValidIsoDate(value: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00Z`);
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value;
}

export function slugifyAscii(value: string): string {
  return value
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/** Deterministic organization slug: ASCII text when available, otherwise a stable hash. */
export function organizationSlugFor(name: string): string {
  const ascii = slugifyAscii(name).slice(0, 80).replace(/-+$/g, '');
  if (ascii.length >= 3) return ascii;
  return `org-${createHash('sha1').update(name).digest('hex').slice(0, 10)}`;
}

export function parseJobInput(body: unknown, validCategorySlugs: string[]): ParseResult<JobInput> {
  const errors: Record<string, string> = {};
  if (typeof body !== 'object' || body === null || Array.isArray(body)) {
    return { ok: false, errors: { _form: 'অনুরোধের তথ্য সঠিক নয়।' } };
  }
  const raw = body as Record<string, unknown>;

  const text = (key: string, label: string, max: number, opts: { required?: boolean; min?: number; multiline?: boolean } = {}): string | undefined => {
    const value = cleanString(raw[key], opts.multiline ?? false);
    if (!value) {
      if (opts.required) errors[key] = `${label} আবশ্যক।`;
      return undefined;
    }
    if (opts.min && value.length < opts.min) errors[key] = `${label} কমপক্ষে ${opts.min} অক্ষরের হতে হবে।`;
    else if (value.length > max) errors[key] = `${label} সর্বোচ্চ ${max} অক্ষরের হতে পারবে।`;
    return value;
  };

  const date = (key: string, label: string, required = false): string | undefined => {
    const value = cleanString(raw[key], false);
    if (!value) {
      if (required) errors[key] = `${label} আবশ্যক।`;
      return undefined;
    }
    if (!isValidIsoDate(value)) {
      errors[key] = `${label} সঠিক তারিখ নয়।`;
      return undefined;
    }
    return value;
  };

  const url = (key: string, label: string): string | undefined => {
    const value = cleanString(raw[key], false);
    if (!value) return undefined;
    if (value.length > 2000 || /\s/.test(value)) {
      errors[key] = `${label} সঠিক URL নয়।`;
      return undefined;
    }
    try {
      const parsed = new URL(value);
      if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') throw new Error('protocol');
      return parsed.href;
    } catch {
      errors[key] = `${label} একটি বৈধ http বা https URL হতে হবে।`;
      return undefined;
    }
  };

  const organization = text('organization', 'প্রতিষ্ঠানের নাম', 150, { required: true, min: 2 });
  const title = text('title', 'চাকরির শিরোনাম', 200, { required: true, min: 5 });

  // Slug (optional; generated by the server when blank)
  let slug: string | undefined;
  const slugRaw = cleanString(raw.slug, false).toLowerCase();
  if (slugRaw) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slugRaw) || slugRaw.length < 3 || slugRaw.length > 100) {
      errors.slug = 'স্লাগে শুধু ছোট হাতের ইংরেজি অক্ষর, সংখ্যা ও হাইফেন ব্যবহার করুন (৩–১০০ অক্ষর)।';
    } else {
      slug = slugRaw;
    }
  }

  // Positions
  const positions: PositionInput[] = [];
  if (raw.positions !== undefined && raw.positions !== null) {
    if (!Array.isArray(raw.positions) || raw.positions.length > 50) {
      errors.positions = 'পদের তালিকা সঠিক নয় (সর্বোচ্চ ৫০টি পদ)।';
    } else {
      for (const item of raw.positions) {
        if (typeof item !== 'object' || item === null) continue;
        const entry = item as Record<string, unknown>;
        const name = cleanString(entry.name, false);
        if (!name) continue;
        if (name.length > 120) {
          errors.positions = 'পদের নাম সর্বোচ্চ ১২০ অক্ষরের হতে পারবে।';
          break;
        }
        const position: PositionInput = { name };
        const vacancyRaw = entry.vacancies;
        if (vacancyRaw !== undefined && vacancyRaw !== null && vacancyRaw !== '') {
          const number = Number(vacancyRaw);
          if (!Number.isInteger(number) || number < 0 || number > 1_000_000) {
            errors.positions = 'পদসংখ্যা ০ থেকে ১০,০০,০০০ এর মধ্যে পূর্ণসংখ্যা হতে হবে।';
            break;
          }
          position.vacancies = number;
        }
        positions.push(position);
      }
    }
  }

  // Total vacancies: explicit value, otherwise the sum of listed vacancies (if any)
  let totalVacancies: number | undefined;
  const totalRaw = raw.totalVacancies;
  if (totalRaw !== undefined && totalRaw !== null && totalRaw !== '') {
    const number = Number(totalRaw);
    if (!Number.isInteger(number) || number < 0 || number > 10_000_000) errors.totalVacancies = 'মোট পদসংখ্যা সঠিক পূর্ণসংখ্যা হতে হবে।';
    else totalVacancies = number;
  } else {
    const listed = positions.filter((position) => position.vacancies !== undefined);
    if (listed.length > 0) totalVacancies = listed.reduce((sum, position) => sum + (position.vacancies ?? 0), 0);
  }

  // Category
  const categorySlug = cleanString(raw.categorySlug, false);
  if (!categorySlug) errors.categorySlug = 'ক্যাটাগরি আবশ্যক।';
  else if (!validCategorySlugs.includes(categorySlug)) errors.categorySlug = 'ক্যাটাগরিটি সঠিক নয়।';

  const applicationStart = date('applicationStart', 'আবেদন শুরুর তারিখ');
  const deadline = date('deadline', 'আবেদনের শেষ তারিখ');
  const publishedAt = date('publishedAt', 'প্রকাশের তারিখ', true);
  if (applicationStart && deadline && deadline < applicationStart) {
    errors.deadline = 'আবেদনের শেষ তারিখ শুরুর তারিখের আগে হতে পারে না।';
  }

  let status: JobStatus | undefined;
  if (raw.status !== undefined && raw.status !== null && raw.status !== '') {
    if (typeof raw.status === 'string' && (JOB_STATUSES as string[]).includes(raw.status)) status = raw.status as JobStatus;
    else errors.status = 'স্ট্যাটাস সঠিক নয়।';
  }

  const input: JobInput = {
    slug,
    organization: organization ?? '',
    title: title ?? '',
    positions,
    totalVacancies,
    categorySlug,
    employmentType: text('employmentType', 'চাকরির ধরন', 60),
    education: text('education', 'শিক্ষাগত যোগ্যতা', 2000, { multiline: true }),
    experience: text('experience', 'অভিজ্ঞতা', 1000, { multiline: true }),
    ageLimit: text('ageLimit', 'বয়সসীমা', 300),
    salary: text('salary', 'বেতন বা গ্রেড', 500),
    applicationFee: text('applicationFee', 'আবেদন ফি', 500),
    applicationStart,
    deadline,
    publishedAt: publishedAt ?? '',
    description: text('description', 'বিস্তারিত বিবরণ', 20000, { multiline: true }),
    howToApply: text('howToApply', 'আবেদন পদ্ধতি', 10000, { multiline: true }),
    applyUrl: url('applyUrl', 'অফিসিয়াল আবেদন লিংক'),
    sourceUrl: url('sourceUrl', 'অফিসিয়াল বিজ্ঞপ্তির উৎস'),
    circularRef: url('circularRef', 'সার্কুলার PDF/ছবির URL'),
    seoTitle: text('seoTitle', 'SEO title', 120),
    metaDescription: text('metaDescription', 'Meta description', 300),
    featuredImage: url('featuredImage', 'Featured image URL'),
    featured: raw.featured === true,
    verified: raw.verified === true,
    status,
  };

  if (Object.keys(errors).length > 0) return { ok: false, errors };
  return { ok: true, value: input };
}

/** Publishing requires at least one official reference so unverifiable jobs are not made public. */
export function checkPublishable(input: JobInput): string | null {
  if (!input.sourceUrl && !input.applyUrl && !input.circularRef) {
    return 'প্রকাশ করতে অন্তত একটি অফিসিয়াল সূত্র (আবেদন লিংক, বিজ্ঞপ্তির উৎস বা সার্কুলার URL) দিতে হবে।';
  }
  return null;
}
